from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, field_validator, model_validator


class InterviewSetupRequest(BaseModel):
    """Candidate interview setup parameters."""

    role: str = Field(
        ...,
        min_length=2,
        max_length=100,
        description="Target job role, e.g., 'Full Stack Developer'",
    )
    experience_level: str = Field(
        default="Mid-Level",
        description="Candidate experience level, e.g., 'Entry-Level', 'Mid-Level', 'Senior', 'Lead'",
    )
    difficulty: str = Field(
        default="Medium",
        description="Target difficulty level, e.g., 'Easy', 'Medium', 'Hard'",
    )
    focus_areas: str = Field(
        ...,
        min_length=2,
        max_length=250,
        description="Focus areas or skills to evaluate, e.g., 'React, TypeScript, Problem Solving'",
    )
    question_count: int = Field(
        default=5,
        ge=3,
        le=5,
        description="Number of questions to generate (between 3 and 5)",
    )
    adaptive: bool = Field(
        default=False,
        description="Whether to use dynamic adaptive question generation where questions are generated dynamically based on candidate performance",
    )
    duration_minutes: Optional[int] = Field(
        default=30,
        ge=5,
        le=120,
        description="Total planned interview duration in minutes (default: 30 minutes)",
    )
    job_description: Optional[str] = Field(
        default=None,
        max_length=5000,
        description="Optional target job description or requirements context",
    )
    interview_mode: Optional[str] = Field(
        default=None,
        description="Explicit interview mode: 'CODING' or 'VERBAL'",
    )

    @field_validator("interview_mode", mode="before")
    @classmethod
    def validate_interview_mode(cls, v: Any) -> Optional[str]:
        if v is None:
            return None
        if isinstance(v, str):
            val = v.strip().upper()
            if val in ("CODING", "CODE", "PROGRAMMING"):
                return "CODING"
            if val in ("VERBAL", "SPEECH", "CONCEPTUAL", "VOICE"):
                return "VERBAL"
            raise ValueError(f"Invalid interview_mode '{v}'. Allowed modes are 'CODING' or 'VERBAL'.")
        return None

    @field_validator("role", "focus_areas")
    @classmethod
    def validate_non_empty(cls, v: str) -> str:
        trimmed = v.strip()
        if not trimmed:
            raise ValueError("Field cannot be empty or contain only whitespace.")
        return trimmed


class QuestionType(str, Enum):
    """Canonical question types supported across InterviewIQ."""

    CODING = "coding"
    VERBAL = "verbal"
    SYSTEM_DESIGN = "system_design"
    SQL = "sql"
    MULTIPLE_CHOICE = "multiple_choice"


class QuestionItem(BaseModel):
    """Structured question model generated by AI."""

    id: str = Field(..., description="Unique question identifier within the session, e.g., 'q_1'")
    question_number: int = Field(..., ge=1, description="Sequential question number (1-indexed)")
    text: str = Field(..., min_length=10, description="Full question text")
    assessed_skill: str = Field(..., min_length=2, description="Specific skill being evaluated")
    normalized_skill: Optional[str] = Field(
        default=None,
        description="Canonical normalized skill name",
    )
    difficulty: str = Field(..., description="Question difficulty, e.g., 'Medium'")
    rubric: str = Field(..., min_length=10, description="Evaluation criteria and strong answer indicators")
    selection_rationale: Optional[str] = Field(
        default=None,
        description="Transparent explanation for why this question was dynamically selected",
    )
    time_band: Optional[str] = Field(
        default=None,
        description="Time constraint category: 'comprehensive', 'focused', or 'concise'",
    )
    gap_category: Optional[str] = Field(
        default=None,
        description="Originating skill gap classification (e.g., 'Mentioned but insufficiently evidenced')",
    )
    role_relevance: Optional[str] = Field(
        default=None,
        description="Relevance to target job role",
    )
    title: Optional[str] = Field(
        default=None,
        description="Problem title, e.g. 'Two Sum'",
    )
    source_evidence: Optional[str] = Field(
        default=None,
        description="Grounded resume evidence reference or verbatim excerpt, if available",
    )
    question_type: str = Field(
        default="verbal",
        description="Type of question: 'coding', 'verbal', 'system_design', 'sql', or 'multiple_choice'",
    )
    response_mode: Optional[str] = Field(
        default=None,
        description="Authoritative response mode ('coding_ide', 'sql_sandbox', 'verbal_speech_text', 'system_design_text', 'multiple_choice')",
    )
    options: Optional[List[str]] = Field(
        default=None,
        description="Selectable option choices for multiple_choice questions",
    )
    function_name: Optional[str] = Field(
        default=None,
        description="Expected function name for function-based DSA problems",
    )
    input_format: Optional[str] = Field(
        default=None,
        description="Input parameters format description",
    )
    output_format: Optional[str] = Field(
        default=None,
        description="Output return value format description",
    )
    code_template: Optional[Any] = Field(
        default=None,
        description="Starter code templates mapped by language key or starter string",
    )
    test_cases: Optional[List[Dict[str, Any]]] = Field(
        default=None,
        description="Test cases for coding questions",
    )
    sql_fixture: Optional[str] = Field(
        default=None,
        description="Identifier for active SQL fixture schema",
    )
    sql_schema: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Schema and table definitions for SQL questions",
    )
    expected_sql_query: Optional[str] = Field(
        default=None,
        description="Benchmark query for SQL evaluation",
    )
    constraints: Optional[List[str]] = Field(
        default=None,
        description="Constraints for coding problems",
    )
    examples: Optional[List[Dict[str, Any]]] = Field(
        default=None,
        description="Example input/output cases",
    )
    available_modes: Optional[List[str]] = Field(
        default=None,
        description="Supported candidate answer modes: 'coding', 'verbal', 'system_design', 'sql', 'multiple_choice'",
    )
    recommended_mode: Optional[str] = Field(
        default=None,
        description="Default recommended answer mode for this question",
    )
    concept: Optional[str] = Field(
        default=None,
        description="Specific concept tested by this question (from ML text assessment model)",
    )
    angle: Optional[str] = Field(
        default=None,
        description="Exact knowledge angle tested (from ML text assessment model)",
    )
    adaptive_action: Optional[str] = Field(
        default=None,
        description="Adaptive action decided by ML model (INCREASE_DIFFICULTY, CLARIFY_CONCEPT, REVISIT_FUNDAMENTALS)",
    )
    adaptive_reason: Optional[str] = Field(
        default=None,
        description="Reason for adaptive decision",
    )
    reference_solution: Optional[str] = Field(
        default=None,
        description="Independently verified reference implementation for oracle execution",
    )
    comparison_policy: Optional[str] = Field(
        default="strict_structural",
        description="Output comparison policy: 'strict_structural', 'unordered_array', 'float_tolerance', 'case_insensitive_string'",
    )
    float_tolerance: Optional[float] = Field(
        default=1e-5,
        description="Numerical tolerance epsilon for float comparison when float_tolerance policy is active",
    )
    oracle_verified: Optional[bool] = Field(
        default=False,
        description="Whether this problem's specification and test cases have been validated by an independent oracle",
    )
    oracle_provenance: Optional[str] = Field(
        default=None,
        description="Provenance of the oracle verification (e.g. 'benchmark_catalog', 'oracle_runner_v1', 'repaired_v1')",
    )
    validation_error: Optional[str] = Field(
        default=None,
        description="Validation failure description if problem specification or oracle check failed",
    )
    quarantined: Optional[bool] = Field(
        default=False,
        description="Flag set to true if the question has conflicting specification or failed oracle verification",
    )

    @model_validator(mode="before")
    @classmethod
    def _validate_classification_and_modes(cls, data: Any) -> Any:
        if isinstance(data, dict):
            from app.core.problem_catalog import normalize_and_classify_question
            session_mode = data.get("session_mode") or data.get("interview_mode")
            return normalize_and_classify_question(data, session_mode=session_mode)
        return data

    def ensure_classification_and_modes(self, session_mode: Optional[str] = None) -> "QuestionItem":
        from app.core.problem_catalog import normalize_and_classify_question
        d = self.model_dump()
        normalized = normalize_and_classify_question(d, session_mode=session_mode)
        if session_mode and session_mode.strip().upper() == "VERBAL":
            self.test_cases = None
            self.code_template = None
            self.function_name = None
            self.input_format = None
            self.output_format = None
            self.constraints = None
            self.examples = None
            self.sql_fixture = None
            self.sql_schema = None
            self.expected_sql_query = None
        for k, v in normalized.items():
            if hasattr(self, k):
                setattr(self, k, v)
        return self

    @field_validator("question_type", mode="before")
    @classmethod
    def normalize_question_type(cls, v: Any) -> str:
        if not v or not isinstance(v, str):
            return "verbal"
        val = v.strip().lower()
        if val in ("coding", "coding_dsa", "dsa", "code"):
            return "coding"
        if val in ("system_design", "sys_design", "architecture", "system-design"):
            return "system_design"
        if val in ("sql", "database"):
            return "sql"
        if val in ("multiple_choice", "mcq"):
            return "multiple_choice"
        if val in ("verbal", "behavioral", "conceptual"):
            return "verbal"
        return "verbal"


