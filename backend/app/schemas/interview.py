class SubmitAnswerRequest(BaseModel):
    """Candidate answer submission schema supporting verbal, coding, and SQL solutions."""

    question_id: str = Field(..., description="ID of the question being answered")
    answer_text: Optional[str] = Field(
        default="",
        max_length=10000,
        description="Candidate's written or transcribed verbal answer",
    )
    code: Optional[str] = Field(
        default=None,
        max_length=50000,
        description="Candidate source code for coding problems",
    )
    language: Optional[str] = Field(
        default=None,
        description="Programming language used for the solution",
    )
    sql_query: Optional[str] = Field(
        default=None,
        max_length=10000,
        description="Candidate SQL query for database questions",
    )
    execution_result: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Recorded execution output or test results",
    )
    answer_mode: Optional[str] = Field(
        default=None,
        description="Candidate selected answer mode: 'coding', 'verbal', 'system_design', 'sql', 'multiple_choice'",
    )

    @field_validator("answer_text")
    @classmethod
    def sanitize_answer(cls, v: Optional[str]) -> str:
        if v is None:
            return ""
        return v.strip()

    @model_validator(mode="after")
    def validate_content_not_empty(self) -> "SubmitAnswerRequest":
        mode = (self.answer_mode or "").strip().lower()
        if mode == "coding":
            if not (self.code and self.code.strip()):
                raise ValueError("Source code is required when submitting in Coding Mode.")
        elif mode == "sql":
            if not (self.sql_query and self.sql_query.strip()):
                raise ValueError("SQL query is required when submitting in SQL Mode.")
        elif mode in ("verbal", "system_design"):
            if not (self.answer_text and self.answer_text.strip()):
                raise ValueError(f"Answer text is required when submitting in {mode.replace('_', ' ').title()} Mode.")
        else:
            has_text = bool(self.answer_text and self.answer_text.strip())
            has_code = bool(self.code and self.code.strip())
            has_sql = bool(self.sql_query and self.sql_query.strip())
            if not (has_text or has_code or has_sql):
                raise ValueError("Answer cannot be empty or contain only whitespace.")
        return self


